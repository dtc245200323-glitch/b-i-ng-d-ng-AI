test('FAQ chatbot answers five topics, typed questions and fits mobile', async ({ page }, info) => {
  await page.route('**/api/v1/**', route => route.fulfill({status: 401, json: {error: {code: 'INVALID_SESSION'}}}))
  await page.goto('/')
  await page.getByRole('button', {name: 'Mở chatbot tư vấn'}).click()
  const dialog = page.getByRole('dialog', {name: 'Tư vấn tự động'})
  await expect(dialog).toBeVisible()
  await expect(page.getByLabel('Nhập câu hỏi tư vấn')).toBeFocused()
  await expect(dialog.getByRole('button', {name: 'Gửi câu hỏi'})).toBeDisabled()
  for (const [question, expected] of [
    ['Trung tâm có những khóa học nào?', 'định hướng IELTS'],
    ['Học phí và cách thanh toán thế nào?', 'mã tham chiếu'],
    ['Tôi xem lịch học ở đâu?', 'Học tập của tôi'],
    ['Làm sao đăng ký học tại trung tâm?', 'mã mời hợp lệ'],
    ['Tôi có thể học thử hoặc kiểm tra trình độ không?', 'do trung tâm xác nhận'],
  ]) {
    await dialog.getByRole('button', {name: question, exact: true}).click()
    await expect(dialog.locator('.ph-chat-message.bot').last()).toContainText(expected)
  }
  await page.getByLabel('Nhập câu hỏi tư vấn').fill('hoc phi bao nhieu?')
  await page.getByLabel('Nhập câu hỏi tư vấn').press('Enter')
  await expect(dialog.locator('.ph-chat-message.bot').last()).toContainText('mã tham chiếu')
  await page.getByLabel('Nhập câu hỏi tư vấn').fill('Hôm nay trời có mưa không?')
  await dialog.getByRole('button', {name: 'Gửi câu hỏi'}).click()
  await expect(dialog.locator('.ph-chat-message.bot').last()).toContainText('chưa có câu trả lời')
  await page.screenshot({path: info.outputPath('faq-desktop.png')})
  await page.getByLabel('Nhập câu hỏi tư vấn').press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('button', {name: 'Mở chatbot tư vấn'})).toBeFocused()
  await page.setViewportSize({width: 360, height: 640})
  await page.getByRole('button', {name: 'Mở chatbot tư vấn'}).click()
  await expect(dialog.locator('.ph-chat-message.bot').last()).toContainText('chưa có câu trả lời')
  const box = await dialog.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.y).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(360)
  await expect(dialog.getByRole('button', {name: 'Gửi câu hỏi'})).toBeInViewport()
  await page.screenshot({path: info.outputPath('faq-mobile.png')})
  await dialog.getByRole('link', {name: 'Đăng ký học'}).click()
  await expect(page).toHaveURL(/\/register$/)
})

